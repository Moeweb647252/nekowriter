//! Typed identifiers.
//!
//! Every entity has its own identifier type, so a version ID can never be passed where a
//! project ID is expected. Identifiers are UUIDs, stored as text in SQLite and sent as
//! strings over the API.

use std::{fmt, str::FromStr};

use sea_orm::DeriveValueType;
use serde::{Deserialize, Serialize};
use ts_rs::TS;
use uuid::Uuid;

macro_rules! id_type {
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        #[derive(
            Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, TS,
            DeriveValueType,
        )]
        #[ts(export, type = "string")]
        #[sea_orm(value_type = "String")]
        pub struct $name(Uuid);

        impl $name {
            /// Generates a new identifier. Version 7 UUIDs are ordered by creation time,
            /// which keeps SQLite primary-key indexes append-mostly.
            #[must_use]
            pub fn generate() -> Self {
                Self(Uuid::now_v7())
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                self.0.fmt(formatter)
            }
        }

        impl FromStr for $name {
            type Err = uuid::Error;

            fn from_str(value: &str) -> Result<Self, Self::Err> {
                Uuid::parse_str(value).map(Self)
            }
        }

        // Required for SeaORM primary keys. Identifiers are generated by the application,
        // never by the database, so a database-assigned integer key is always an error.
        impl sea_orm::TryFromU64 for $name {
            fn try_from_u64(_: u64) -> Result<Self, sea_orm::DbErr> {
                Err(sea_orm::DbErr::ConvertFromU64(stringify!($name)))
            }
        }
    };
}

id_type!(
    /// Identifies a project.
    ProjectId
);

id_type!(
    /// Identifies a version (an independent manuscript) inside a project.
    VersionId
);

id_type!(
    /// Identifies one user action. The client generates it and reuses it when it retries
    /// the same action, which makes every command idempotent.
    CommandId
);
