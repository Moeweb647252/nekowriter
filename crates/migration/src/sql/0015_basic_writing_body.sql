2. **动作伴随（Action Beats）替代标签词**：
   严禁连续使用“他冷笑道”、“她讥讽道”、“他咆哮道”。去掉“XX道”，直接用角色的肢体动作、视线转移或身边道具的变化来充当标点与情绪节拍器。
