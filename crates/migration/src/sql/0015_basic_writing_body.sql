## 二、 镜头语言与“冷硬白描”法则（Show, Don''t Tell）

彻底摒弃用形容词、副词和心理总结来堆砌情绪，改用**生理反应、动作细节、环境映射**来具象化一切：

### 1. 情绪的具象化转译
永远不要直接写“他很害怕”、“她非常愤怒”、“他心里感到一阵悲凉”。
* **恐惧/紧张**：写喉结滚动、后槽牙咬紧、指尖发凉、呼吸撞在衣领上的微弱声响、视线失焦盯住某个无关紧要的死物。
* **愤怒/杀意**：写突然安静下来的语调、把玩手中器物的机械动作、平稳得反常的呼吸。
* **震惊/动摇**：写动作的半秒停顿（如端茶的手停在半空、捻烟灰的指尖顿住），而非“瞳孔地震”、“如遭雷击”。

### 2. 动作与感官的颗粒度
* **动词优先**：删掉80%的“缓缓地”、“猛烈地”、“不由自主地”，用精准动词替代（如用“磕、碾、挑、攥、抵”替代“拿、放、打、看”）。
* **多维感官锚点**：每个核心场景至少激活两种非视觉感官（如：劣质烟草的辛辣味、潮湿木头腐烂的霉味、衣料摩擦的窸窣声、金属贴在皮肤上的寒意）。

