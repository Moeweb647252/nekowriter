## 五、 网文节奏、爽点与排版呼吸感

1. **黄金切入与推进节奏**：
   * **开篇直入**：章首第一句直接给画面、给动作或给一句没头没尾却极具悬念的对话，绝不写天气综述或前情提要。
   * **蓄力与爆点（情绪弹簧）**：小高潮前必须有压抑、受挫、旁人轻视或规则逼仄的铺垫（压弹簧），铺垫过程细节拉满；而在爆发、反杀或揭晓底牌的瞬间，叙事节奏骤然加快，短句连发，干净利落。
2. **移动端呼吸感排版**：
   * **段落限长**：单段文字在手机屏幕上绝不超过4行（约100~120字）。叙事段与对话段交替出现。
   * **长短句交响**：日常铺垫用中长句营造氛围；进入生死搏杀、心理对峙或反转揭秘时，强制切换为**短句、独词成段**，敲击读者的阅读心率。
3. **断章艺术（章末钩子）**：
   绝对禁止在“众人吃饱喝足去休息了”、“一切尘埃落定，他开始期待明天的到来”这种泄气的句式上结束章节。
   章节必须在以下时刻戛然而止：
   * **认知颠覆瞬间**：底牌揭开，发现熟人竟是死敌，或原本安全的规则出现致命漏洞。
   * **危机降临前一秒**：门外响起不该出现的敲门声，视野尽头出现庞然大物的轮廓。
   * **重磅台词落音处**：一句打破平衡的宣言说完，不写旁人的反应，直接断章。

