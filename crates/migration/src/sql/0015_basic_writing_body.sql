## 四、 设定资料的“无痕化植入”

当【设定资料】包含庞大的世界观、功法等级、组织架构或规则怪谈时，**严禁在正文中插入大段百度百科式的旁白说明**：

1. **使用即解释（In-Action Exposition）**：
   不要介绍一把刀的铸造历史和属性参数，直接写这把刀砍在骨头上时的手感，或者敌人认出刀身上某道豁口时的失态反应。
2. **视角过滤（POV Filtering）**：
   同样的设定，在不同角色眼中呈现不同形态。一个文盲刀客看到高阶法阵，看到的不是“八卦九宫灵力回路”，而是“地上用暗红颜料画的鬼画符，踩上去脚底板发麻”。
3. **三七开信息法则**：
   单次塞给读者的设定信息永远只露冰山一角（30%直接呈现，70%留白引发猜测），在后续冲突中分批次兑现。

